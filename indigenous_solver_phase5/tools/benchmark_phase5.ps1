param(
  [string]$ModelsPath = "benchmarks\netlib",
  [string]$Phase2Exe = "indigenous_solver_phase2\build\Release\solver_phase2_cli.exe",
  [string]$Phase3Exe = "indigenous_solver_phase3\build\Release\solver_phase3_cli.exe",
  [string]$Phase5BenchmarkExe = "indigenous_solver_phase5\build\Release\indigenous_phase5_end_to_end_benchmark.exe",
  [string]$OutputCsv = "benchmarks\netlib\phase5_end_to_end_comparison.csv",
  [string]$OutputSummaryCsv = "benchmarks\netlib\phase5_end_to_end_summary.csv",
  [string]$OutputReport = "benchmarks\netlib\phase5_end_to_end_report.md"
)

$models = @("afiro","adlittle","blend","bore3d","brandy","grow15","kb2","lotfi","sc50b","share1b")

function Invoke-Solver($exe, $model) {
  if (!(Test-Path $exe)) { throw "Executable not found: $exe" }
  $path = Join-Path $ModelsPath ($model + ".mps")
  return ((& $exe solve $path 2>&1) -join [Environment]::NewLine)
}
function Metric([string]$text, [string]$pattern) {
  $m = [regex]::Match($text, $pattern)
  if (!$m.Success) { throw "Metric not found: $pattern" }
  return $m.Groups[1].Value.Trim()
}
function Optional([string]$text, [string]$pattern) {
  $m = [regex]::Match($text, $pattern)
  if (!$m.Success) { return "" }
  return $m.Groups[1].Value.Trim()
}

if (!(Test-Path $Phase5BenchmarkExe)) { throw "Phase 5.9 benchmark executable not found: $Phase5BenchmarkExe" }

$rows = @()
foreach ($model in $models) {
  Write-Host "===== $model ====="
  $p2 = Invoke-Solver $Phase2Exe $model
  $p3 = Invoke-Solver $Phase3Exe $model
  $p2Time = [double](Metric $p2 "(?m)^Timing total_ms:\s*(.+)$")
  $p3Time = [double](Metric $p3 "(?m)^Timing total_ms:\s*(.+)$")
  $p2Obj = [double](Metric $p2 "(?m)^Objective:\s*(.+)$")
  $p3Obj = [double](Metric $p3 "(?m)^Objective:\s*(.+)$")
  $p2Cert = Metric $p2 "(?m)^Certificate:\s*(.+)$"
  $p3Cert = Metric $p3 "(?m)^Certificate:\s*(.+)$"
  $p2Iter = [int](Metric $p2 "(?m)^Iterations:\s*(.+)$")
  $p3Iter = [int](Metric $p3 "(?m)^Iterations:\s*(.+)$")
  $backend = Optional $p3 "(?m)^Pricing backend:\s*(.+)$"
  $speedup = if ($p3Time -gt 0) { $p2Time / $p3Time } else { 0 }
  $rows += [pscustomobject]@{
    model=$model
    phase2_ms=$p2Time
    phase3_ms=$p3Time
    phase3_speedup=[math]::Round($speedup,4)
    phase2_iterations=$p2Iter
    phase3_iterations=$p3Iter
    objective_difference=[math]::Abs($p2Obj-$p3Obj)
    phase2_certificate=$p2Cert
    phase3_certificate=$p3Cert
    phase3_backend=$backend
  }
  Write-Host ("P2 {0:N4} ms | P3 {1:N4} ms | Speedup {2:N2}x | Backend {3} | Cert {4}" -f $p2Time,$p3Time,$speedup,$backend,$p3Cert)
}

$parent = Split-Path $OutputCsv -Parent
if ($parent -and !(Test-Path $parent)) { New-Item -ItemType Directory -Path $parent -Force | Out-Null }
$rows | Export-Csv $OutputCsv -NoTypeInformation
$total2 = ($rows | Measure-Object phase2_ms -Sum).Sum
$total3 = ($rows | Measure-Object phase3_ms -Sum).Sum
$wins = @($rows | Where-Object {$_.phase3_ms -lt $_.phase2_ms}).Count
$certs = @($rows | Where-Object {$_.phase3_certificate -eq "PASS"}).Count
$maxDiff = ($rows | Measure-Object objective_difference -Maximum).Maximum
$aggregate = if ($total3 -gt 0) {$total2/$total3} else {0}

$summary = [pscustomobject]@{
  models=$rows.Count
  phase2_total_ms=[math]::Round($total2,4)
  phase3_total_ms=[math]::Round($total3,4)
  aggregate_speedup=[math]::Round($aggregate,4)
  phase3_wins=$wins
  phase3_certificates_pass=$certs
  max_objective_difference=$maxDiff
  note="Phase 3 uses CPU fallback when CUDA is unavailable; no GPU acceleration is claimed."
}
$summary | Export-Csv $OutputSummaryCsv -NoTypeInformation

$bench = ((& $Phase5BenchmarkExe 128 100 16 2>&1) -join [Environment]::NewLine)
$bench | Set-Content "benchmarks\netlib\phase5_pipeline_benchmark_output.txt" -Encoding UTF8
if ($LASTEXITCODE -ne 0) { throw "Phase 5.9 pipeline benchmark failed." }

$report = @(
"# Phase 5.9 End-to-End GPU/CPU Benchmark Report","",
"Generated by `indigenous_solver_phase5/tools/benchmark_phase5.ps1`.",
"",
"## Phase 2 vs Phase 3 model benchmark","",
"| Metric | Result |","|---|---:|",
"| Models | $($rows.Count) |",
"| Phase 2 total | $([math]::Round($total2,4)) ms |",
"| Phase 3 total | $([math]::Round($total3,4)) ms |",
"| Aggregate Phase 3 speedup | $([math]::Round($aggregate,4))x |",
"| Phase 3 faster models | $wins / $($rows.Count) |",
"| Phase 3 certificates PASS | $certs / $($rows.Count) |",
"| Maximum objective difference | $maxDiff |",
"",
"## Per-model results","",
"| Model | P2 ms | P3 ms | Speedup | P3 Backend | P3 Cert |",
"|---|---:|---:|---:|---|---|"
)
foreach ($r in $rows) {
  $report += "| $($r.model) | $([math]::Round($r.phase2_ms,4)) | $([math]::Round($r.phase3_ms,4)) | $([math]::Round($r.phase3_speedup,4))x | $($r.phase3_backend) | $($r.phase3_certificate) |"
}
$report += @("","## Phase 5 unified pipeline benchmark","",$bench,"","## Interpretation","")
$report += "- Phase 5.9 validates the existing end-to-end model path through Phase 2/3 and separately exercises the unified Phase 5 linear-algebra pipeline."
$report += "- CUDA execution is reported only when the underlying Phase 3/4 backends are actually CUDA-active."
$report += "- On an Intel-only machine, Phase 3/Phase 5 results are CPU fallback measurements, not NVIDIA GPU acceleration."
$report | Set-Content $OutputReport -Encoding UTF8

Write-Host ""
Write-Host "=== Phase 5.9 End-to-End Benchmark Summary ==="
Write-Host ("Models: {0} | P3 faster: {1} | Certificates PASS: {2}/{0}" -f $rows.Count,$wins,$certs)
Write-Host ("Phase2 total: {0:N4} ms | Phase3 total: {1:N4} ms | Aggregate speedup: {2:N2}x" -f $total2,$total3,$aggregate)
Write-Host "Phase 5 pipeline benchmark saved to benchmarks\netlib\phase5_pipeline_benchmark_output.txt"
Write-Host "CSV: $OutputCsv"
Write-Host "Summary: $OutputSummaryCsv"
Write-Host "Report: $OutputReport"
